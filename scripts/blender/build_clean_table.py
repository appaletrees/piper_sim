def make_mesh(name,vertices,faces,material,uv=None):
    me=bpy.data.meshes.new(name);me.from_pydata(vertices,[],faces);me.update()
    obj=bpy.data.objects.new(name,me);scene.collection.objects.link(obj)
    obj.data.materials.append(blender_mats[material]);obj['material_key']=material
    if uv is not None:
        layer=me.uv_layers.new(name='UVMap')
        for poly in me.polygons:
            for loop in poly.loop_indices: layer.data[loop].uv=uv[me.loops[loop].vertex_index]
    # Weld duplicated box faces and lathe seams; preserve per-loop UV seams.
    bm=bmesh.new();bm.from_mesh(me)
    bmesh.ops.remove_doubles(bm,verts=list(bm.verts),dist=1e-8)
    bmesh.ops.dissolve_limit(bm,angle_limit=.002,verts=list(bm.verts),edges=list(bm.edges),delimit={'UV'})
    bm.to_mesh(me);bm.free();me.update()
    for poly in me.polygons: poly.use_smooth=True
    if uv is None:
        select(obj);bpy.ops.object.mode_set(mode='EDIT');bpy.ops.mesh.select_all(action='SELECT')
        bpy.ops.uv.smart_project(angle_limit=math.radians(66),island_margin=.025)
        bpy.ops.object.mode_set(mode='OBJECT')
    return obj


def bevel(obj,width,segments=3):
    mod=obj.modifiers.new('Manufactured edge radii','BEVEL');mod.width=width;mod.segments=segments
    mod.limit_method='ANGLE';mod.angle_limit=math.radians(24)
    mod.harden_normals=True
    select(obj);bpy.ops.object.modifier_apply(modifier=mod.name)
    wn=obj.modifiers.new('Weighted corner normals','WEIGHTED_NORMAL');wn.keep_sharp=True;wn.weight=30
    bpy.ops.object.modifier_apply(modifier=wn.name)


def cube(name,size,position,material,radius=.0005):
    bpy.ops.mesh.primitive_cube_add(size=1,location=position)
    obj=bpy.context.object;obj.name=name;obj.scale=size
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    obj.data.materials.append(blender_mats[material]);obj['material_key']=material
    if radius: bevel(obj,radius,5)
    for p in obj.data.polygons:p.use_smooth=True
    return obj


def cylinder(name,radius,depth,position,material,axis='Z'):
    bpy.ops.mesh.primitive_cylinder_add(vertices=64,radius=radius,depth=depth,location=position)
    obj=bpy.context.object;obj.name=name
    if axis=='X':obj.rotation_euler[1]=math.pi/2
    obj.data.materials.append(blender_mats[material]);obj['material_key']=material
    bevel(obj,min(radius*.12,.0003),3)
    for p in obj.data.polygons:p.use_smooth=True
    return obj


def torus(name,major,minor,z,material,rotation=None,position=None):
    bpy.ops.mesh.primitive_torus_add(major_segments=128,minor_segments=12,
        major_radius=major,minor_radius=minor,location=position or (0,0,z))
    obj=bpy.context.object;obj.name=name
    if rotation:obj.rotation_euler=rotation
    obj.data.materials.append(blender_mats[material]);obj['material_key']=material
    for p in obj.data.polygons:p.use_smooth=True
    return obj


def new_charger(spec):
    x,y,z=spec['size_m']
    result=[cube('abs_lower_half',[x,y,z*.49],[0,0,z*.245],'charger_white',.0045),
            cube('abs_upper_half',[x,y,z*.50],[0,0,z*.75],'charger_white',.0045),
            cube('mould_split_line',[x-.0007,y-.0007,.00045],[0,0,z*.495],'charger_panel',.00015),
            cube('folded_prong_panel',[x*.40,y*.28,.0012],[-x*.23,y*.26,z-.0006],'charger_panel',.001),
            cube('folded_prong_insert',[x*.37,y*.25,.0012],[-x*.23,y*.26,z-.0005],'charger_white',.001),
            cube('usb_port_surround',[.0003,.012,.005],[x/2-.00005,0,z*.5],'pen_metal',.00014),
            cube('usb_port_opening',[.0004,.009,.0028],[x/2+.00004,0,z*.5],'rubber',.00018),
            cube('usb_port_tongue',[.0005,.006,.00045],[x/2+.00010,0,z*.5],'charger_panel',.0001)]
    # Irregular remnants on the cover, matching the worn label in the photo.
    for i,(cx,cy,rx,ry) in enumerate([(.003,-.006,.0024,.0012),(.010,-.010,.003,.0015),(.014,-.015,.002,.002)]):
        pts=[(cx+rx*(1+.18*math.sin(a*7))*math.cos(a),cy+ry*(1+.15*math.cos(a*5))*math.sin(a),z+.00004)
             for a in np.linspace(0,2*math.pi,25)[:-1]]
        result.append(make_mesh('adhesive_trace_'+str(i),pts,[list(range(len(pts)))],'label_wear'))
    return result


